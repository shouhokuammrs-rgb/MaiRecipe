/** 前後の空白と、よくある飾り（◎ ・ ★ など）を落として、辞書で1つの名前にそろえる */
export function canonicalName(raw: string): string {
  const s = raw
    .trim()
    .replace(/^[◎○●・★☆◆◇■□※\-‐–—*]+/, "")
    .replace(/[（(][^）)]*[）)]$/, "")
    .trim();
  return ALIASES[s] ?? s;
}

